DRUM_NOTES = {
    "kick": 36, "snare": 38, "clap": 39, "hat": 42, "openhat": 46,
    "lowtom": 45, "midtom": 47, "hightom": 50, "ride": 51, "crash": 49,
}


def _folder(*parts: str) -> Path:
    path = OUT.joinpath(*parts)
    path.mkdir(parents=True, exist_ok=True)
    return path


def _write(relative: str, data: bytes) -> None:
    path = OUT / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def _drum_hit(track: MidiTrack, tick: int, name: str, velocity: int | None = None,
              duration: int = 30, humanize: bool = True) -> None:
    pitch = DRUM_NOTES[name]
    if velocity is None:
        velocity = rng.randint(92, 122) if name in ("snare", "clap", "crash") else rng.randint(76, 112)
    offset = rng.randint(-8, 8) if humanize else 0
    tick = max(0, tick + offset)
    track.note(tick, pitch, duration, velocity, channel=9)


def _house_groove(bpm: float = 124.0, bars: int = 8, name: str = "Drums",
                  energetic: bool = True) -> MidiTrack:
    track = MidiTrack().track_name(name).tempo(0, bpm).time_signature(0, 4, 4)
    beat = 480
    for bar in range(bars):
        base = bar * 4 * beat
        for b in range(4):
            _drum_hit(track, base + b * beat, "kick", 120 if b in (0, 2) else 112)
        for b in (1, 3):
            _drum_hit(track, base + b * beat, "clap", 112)
            _drum_hit(track, base + b * beat, "snare", 105)
        for eighth in range(8):
            if energetic or eighth % 2 == 0:
                _drum_hit(track, base + eighth * (beat // 2), "hat", 70 + (eighth % 3) * 8)
        _drum_hit(track, base + int(beat * 2.5), "openhat", 92)
        if bar % 4 == 3:
            _drum_hit(track, base + int(beat * 3.5), "openhat", 90)
    track.end(bars * 4 * beat)
    return track


def _breakbeat(bpm: float = 90.0, bars: int = 6) -> MidiTrack:
    track = MidiTrack().track_name("Breakbeat Kit").tempo(0, bpm).time_signature(0, 4, 4)
    beat = 480
    for bar in range(bars):
        base = bar * 4 * beat
        for pos, velocity in ((0, 120), (1.5, 105), (2.75, 108)):
            _drum_hit(track, base + int(pos * beat), "kick", velocity)
        for pos in (1, 3):
            _drum_hit(track, base + int(pos * beat), "snare", 115)
        for step in range(8):
            _drum_hit(track, base + step * (beat // 2), "hat", 65 + (step % 4) * 7)
    track.end(bars * 4 * beat)
    return track


def _fill(bpm: float = 110.0, pitches: bool = True) -> MidiTrack:
    track = MidiTrack().track_name("Tom Fill").tempo(0, bpm).time_signature(0, 4, 4)
    beat = 480
    for bar in range(2):
        base = bar * 4 * beat
        for b in range(4):
            _drum_hit(track, base + b * beat, "kick", 105)
        for b in (1, 3):
            _drum_hit(track, base + b * beat, "snare", 108)
        for step in range(16):
            pos = base + int(step * beat / 4)
            note = "lowtom" if step < 6 else "midtom" if step < 11 else "hightom"
            if pitches:
                _drum_hit(track, pos, note, 80 + step * 3, 20)
            else:
                _drum_hit(track, pos, "snare", 74 + step * 3, 20)
    track.end(2 * 4 * beat)
    return track


