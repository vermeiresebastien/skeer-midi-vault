def _bassline(bpm: float, name: str, program: int = 34, bars: int = 8,
              root: int = 36, pattern_name: str = "funk") -> MidiTrack:
    track = MidiTrack().track_name(name).program(0, program).tempo(0, bpm).time_signature(0, 4, 4)
    beat = 480
    if pattern_name == "funk":
        degrees = [0, 0, 3, 5, 7, 5, 3, 0, 0, 10, 7, 5, 3, 5, 7, 10]
        for bar in range(bars):
            for step, degree in enumerate(degrees):
                tick = bar * 4 * beat + int(step * beat / 2)
                duration = 100 if step % 4 else 170
                track.note(tick, root + degree, duration, rng.randint(88, 112), channel=0)
    elif pattern_name == "walking":
        degrees = [0, 4, 7, 9, 11, 9, 7, 4]
        for bar in range(bars):
            for step, degree in enumerate(degrees):
                tick = bar * 4 * beat + int(step * beat / 2)
                track.note(tick, root + degree, 200, 75 + (step % 3) * 8)
    else:
        degrees = [0, 0, 0, 0, 7, 0, 5, 3]
        for bar in range(bars):
            for step, degree in enumerate(degrees):
                tick = bar * 4 * beat + int(step * beat / 2)
                track.note(tick, root + degree, 180, 88)
    track.end(bars * 4 * beat)
    return track


def _chords(bpm: float, name: str, program: int = 4, bars: int = 8,
            pattern: str = "maj7") -> MidiTrack:
    track = MidiTrack().track_name(name).program(0, program).tempo(0, bpm).time_signature(0, 4, 4)
    beat = 480
    progressions = {
        "maj7": [(60, 64, 67, 71), (57, 60, 64, 67), (53, 57, 60, 64), (55, 59, 62, 65)],
        "minor": [(57, 60, 64), (53, 57, 60), (55, 59, 62), (57, 60, 64)],
        "pop": [(60, 64, 67), (55, 59, 62), (57, 60, 64), (53, 57, 60)],
    }
    chords = progressions.get(pattern, progressions["maj7"])
    for bar in range(bars):
        base = bar * 4 * beat
        chord = list(chords[bar % len(chords)])
        if rng.random() < 0.2:
            chord = [p + 12 for p in chord]
        for i, pitch in enumerate(chord):
            track.note(base, pitch, int(beat * 3.6), rng.randint(55, 76) + i * 3)
            track.note(base + int(beat * 2.0), pitch, int(beat * 1.6), 46 + i * 2)
    track.end(bars * 4 * beat)
    return track


def _arp(bpm: float, name: str, program: int = 0, bars: int = 8,
         root: int = 60, quality: str = "minor") -> MidiTrack:
    intervals = [0, 3, 7, 12, 15, 19, 24, 19, 15, 12, 7, 3] if quality == "minor" else [
        0, 4, 7, 12, 16, 19, 24, 19, 16, 12, 7, 4
    ]
    track = MidiTrack().track_name(name).program(0, program).tempo(0, bpm).time_signature(0, 4, 4)
    beat = 480
    for bar in range(bars):
        for step in range(8):
            pitch = root + intervals[(step + bar * 2) % len(intervals)]
            track.note(bar * 4 * beat + int(step * beat / 2), pitch, 180,
                       rng.randint(70, 105))
    track.end(bars * 4 * beat)
    return track


def _melody(bpm: float, name: str, program: int = 73, bars: int = 8,
            root: int = 72, time_signature: tuple[int, int] = (4, 4),
            swing: bool = False) -> MidiTrack:
    track = MidiTrack().track_name(name).program(0, program).tempo(0, bpm)
    track.time_signature(0, *time_signature)
    numerator, denominator = time_signature
    beat = 480
    bar_ticks = int(beat * numerator * 4 / denominator)
    scale = [0, 2, 4, 5, 7, 9, 11, 12]
    contour = [0, 2, 4, 3, 5, 4, 2, 1, 0, 3, 5, 7, 5, 4, 2, 0]
    for bar in range(bars):
        base = bar * bar_ticks
        for step, degree in enumerate(contour):
            pos = base + int(step * bar_ticks / len(contour))
            if swing and step % 2 == 1:
                pos += int(bar_ticks / len(contour) * 0.16)
            duration = int(bar_ticks / 12)
            track.note(pos, root + scale[degree % len(scale)],
                       duration, rng.randint(72, 108))
    track.end(bars * bar_ticks)
    return track


