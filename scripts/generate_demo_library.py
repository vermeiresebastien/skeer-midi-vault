def _corrupt_second_chunk() -> bytes:
    first = _exercise(120, "Readable First Track")
    second = MidiTrack().raw(0, b"\x90\x3C\x64")  # note-on without an off, then EOT
    good = build_smf([first], midi_format=1)
    header_length = int.from_bytes(good[4:8], "big")
    payload = second.to_bytes(running_status=False, add_end=True)
    chunk = b"MTrk" + len(payload).to_bytes(4, "big") + payload
    # Corrupt declared chunk length and truncate the bytes.
    broken = b"MTrk" + (len(payload) + 100).to_bytes(4, "big") + payload[:-2]
    header = good[:8 + header_length]
    header = header[:10] + (2).to_bytes(2, "big") + header[12:]
    return header + good[8 + header_length:] + broken


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    labels: list[dict[str, object]] = []

    def write_and_label(relative: str, data: bytes, instrument: str, role: str,
                        note: str = "", category: str = "") -> None:
        _write(relative, data)
        labels.append({
            "path": relative,
            "instrument": instrument,
            "role": role,
            "note": note,
            "category": category or "evaluation",
        })

    # Drums -----------------------------------------------------------------
    write_and_label("Drums/Deep House Groove 124.mid", build_smf([_house_groove(124, 8)], midi_format=0),
                    "Drums/percussion", "Drum groove", "Four-on-the-floor house kit", "evaluation")
    write_and_label("Drums/Dusty Breakbeat 90.mid", build_smf([_breakbeat(90, 6)], midi_format=0),
                    "Drums/percussion", "Drum groove", "Syncopated breakbeat kit", "evaluation")
    write_and_label("Drums/Tom Fill 110.mid", build_smf([_fill(110, True)], midi_format=0),
                    "Drums/percussion", "Drum fill", "Two-bar rapid tom fill", "evaluation")
    write_and_label("Drums/Snare Roll Fill 100.mid", build_smf([_snare_roll_fill(100)], midi_format=0),
                    "Drums/percussion", "Drum fill", "One-bar accelerating snare roll", "evaluation")
    trap = MidiTrack().track_name("Trap Hats").tempo(0, 140).time_signature(0, 4, 4)
    for bar in range(4):
        base = bar * 4 * 480
        _drum_hit(trap, base, "kick", 118)
        _drum_hit(trap, base + 960, "kick", 110)
        _drum_hit(trap, base + 480, "snare", 100)
        _drum_hit(trap, base + 1440, "snare", 100)
        for step in range(16):
            if step % 4 == 3:
                continue
            _drum_hit(trap, base + step * 120, "hat", 55 + (step % 4) * 6, 20)
    trap.end(4 * 4 * 480)
    write_and_label("Drums/Trap Hat Pattern 140.mid", build_smf([trap], midi_format=0),
                    "Drums/percussion", "Drum groove", "Hi-hat subdivisions", "evaluation")

    # Bass ------------------------------------------------------------------
    write_and_label("Bass/Funk Bassline F.mid",
                    build_smf([_bassline(108, "Funk Bass", 34, 8, 36, "funk")], midi_format=0),
                    "Bass", "Bassline", "Syncopated funk bass in F", "evaluation")
    write_and_label("Bass/Sub Pulse 808.mid",
                    build_smf([_bassline(130, "808 Sub", 38, 4, 31, "sub")], midi_format=0),
                    "Bass", "Bassline", "Sparse low sub pulse", "evaluation")
    write_and_label("Bass/Walking Upright C.mid",
                    build_smf([_bassline(96, "Walking Upright", 32, 8, 36, "walking")], midi_format=0),
                    "Bass", "Bassline", "Jazz walking bass", "evaluation")
    write_and_label("Bass/Missing Program Bass.mid", _missing_program_bass(),
                    "Bass", "Bassline", "No program changes; name and register only", "evaluation")

    # Keys ------------------------------------------------------------------
    write_and_label("Keys/Rhodes Chords Cmaj7.mid",
                    build_smf([_chords(92, "Rhodes Chords", 4, 8, "maj7")], midi_format=0),
                    "Piano/keys", "Chord progression", "Repeated Rhodes voicings", "evaluation")
    write_and_label("Keys/Piano Arpeggio Am.mid",
                    build_smf([_arp(120, "Piano Arpeggio", 0, 8, 57, "minor")], midi_format=0),
                    "Piano/keys", "Arpeggio", "Eighth-note broken chords", "evaluation")
    write_and_label("Keys/Warm Piano Chords.mid",
                    build_smf([_chords(76, "Warm Piano", 0, 8, "pop")], midi_format=0),
                    "Piano/keys", "Chord progression", "Slow pop piano voicings", "evaluation")
    write_and_label("Keys/Sustain Piano.mid", _sustain_piano(),
                    "Piano/keys", "Pad/sustained harmony", "Sustain pedal holds chord notes", "evaluation")

